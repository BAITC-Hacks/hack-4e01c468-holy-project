const actionCopy = new Map([
  ['finalize', ['сохранение прогноза', 'болжамды сақтауды']],
  ['continue', ['продолжение запуска', 'іске қосуды жалғастыруды']],
  ['use_baseline', ['использование базовой модели', 'негізгі модельге ауысуды']],
  ['abort', ['остановку запуска', 'іске қосуды тоқтатуды']],
]);

function localeIndex(locale) {
  return locale === 'kk' ? 1 : 0;
}

function code(value) {
  return typeof value === 'string' ? value.trim().toLowerCase() : '';
}

function choose(copy, locale) {
  return copy[localeIndex(locale)];
}

function deterministicDecision(action, locale) {
  const selected = actionCopy.get(code(action));
  if (!selected) return null;
  if (locale === 'kk') {
    return `Сыртқы талдау қолданылмады: кіріктірілген ережелер ${selected[1]} таңдады.`;
  }
  return `Внешний анализ не использовался: встроенные правила выбрали ${selected[0]}.`;
}

function successfulAnalysis(action, locale) {
  if (code(action) === 'finalize') return choose(successfulStages.get('analyze_result'), locale);
  return locale === 'kk'
    ? 'Талдау аяқталды: іске қосу үшін келесі әрекет таңдалды.'
    : 'Анализ завершён: выбрано следующее действие запуска.';
}

export function eventReasonExplanation(event, locale = 'ru') {
  const state = code(event?.state);
  const outcome = code(event?.outcome);
  const action = code(event?.action);
  const reason = typeof event?.reason === 'string' ? event.reason.trim().toLowerCase() : '';
  const language = locale === 'kk' ? 'kk' : 'ru';

  if (!successfulStages.has(state)) return choose(neutralCopy, language);

  if (state === 'analyze_result') {
    if (outcome === 'success' || outcome === 'succeeded' || outcome === 'completed') {
      return successfulAnalysis(action, language);
    }
    if (outcome === 'skipped' || reason.startsWith('deterministic_fallback:')) {
      return deterministicDecision(action, language) ?? choose(neutralCopy, language);
    }
    if (reason.includes('invalid_decision') || outcome === 'rejected') {
      return language === 'kk'
        ? 'Талдау жауабы тексеруден өтпеді; кіріктірілген ережелердің шешімі қолданылды.'
        : 'Решение анализа не прошло проверку; применено решение встроенных правил.';
    }
    if (reason.startsWith('analyzer_unavailable:')) {
      if (reason === 'analyzer_unavailable:timeouterror') {
        return language === 'kk'
          ? 'Талдау қызметі уақытында жауап бермеді; кіріктірілген ережелердің қосалқы шешімі қолданылды.'
          : 'Сервис анализа не ответил вовремя; применено резервное решение встроенных правил.';
      }
      return language === 'kk'
        ? 'Сыртқы талдау қолжетімсіз болды; кіріктірілген ережелердің шешімі қолданылды.'
        : 'Внешний анализ недоступен; применено решение встроенных правил.';
    }
  }

  if (state === 'check_for_updates') {
    if (reason.includes('matching_forecast_reused')) {
      return language === 'kk'
        ? 'Деректер өзгермеген; сақталған болжам қайта пайдаланылды.'
        : 'Данные не изменились; сохранённый прогноз использован повторно.';
    }
    if (reason.includes('fingerprints_changed')) {
      return language === 'kk'
        ? 'Кіріс деректер немесе модель өзгерген; жаңа болжам есептеледі.'
        : 'Входные данные или модель изменились; будет рассчитан новый прогноз.';
    }
    if (reason.includes('reuse_identity_unavailable')) {
      return language === 'kk'
        ? 'Қайта пайдалануды қауіпсіз тексеруге қажет сәйкестендіргіштер жоқ; жаңа болжам есептеледі.'
        : 'Не хватает идентификаторов для безопасного повторного использования; будет рассчитан новый прогноз.';
    }
    if (reason.includes('update_check_failed')) {
      return language === 'kk'
        ? 'Қайта пайдалану мүмкіндігін тексеру сәтсіз аяқталды; жаңа болжам есептеледі.'
        : 'Не удалось проверить возможность повторного использования; расчёт нового прогноза продолжается.';
    }
  }

  if (reason.startsWith('operation_failed:')) {
    return choose(failureByStage.get(state) ?? neutralCopy, language);
  }

  if (outcome === 'success' || outcome === 'succeeded' || outcome === 'completed') {
    return state === 'analyze_result'
      ? successfulAnalysis(action, language)
      : choose(successfulStages.get(state), language);
  }

  if (outcome === 'failed' || outcome === 'error') {
    return language === 'kk'
      ? 'Қадам орындалу қатесіне байланысты аяқталмады; толық жазба техникалық деректерде қолжетімді.'
      : 'Шаг не завершился из-за ошибки выполнения; точная запись доступна в технических деталях.';
  }

  if (outcome === 'skipped') {
    return language === 'kk'
      ? 'Бұл қадам орындалмады; толық жазба техникалық деректерде қолжетімді.'
      : 'Этот шаг не выполнялся; точная запись доступна в технических деталях.';
  }

  return choose(neutralCopy, language);
}

export function eventDiagnosticLabels(locale = 'ru') {
  return locale === 'kk'
    ? { disclosure: 'Диагностика үшін', reason: 'Бастапқы жазба', runId: 'Іске қосу ID' }
    : { disclosure: 'Для диагностики', reason: 'Исходная запись', runId: 'Идентификатор запуска' };
}
